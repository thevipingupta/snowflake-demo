-- =============================================================================
-- 01_bronze.sql  (Snowflake)  -- BRONZE layer and CONTROL load/drift logs
-- =============================================================================
-- Purpose : raw landing tables for the Five9 exports and the WFM extract.
-- Source  : docs/source_column_map.csv (generated from reference/Contact_Center.xlsx).
--
-- Conventions (decided here; see CLAUDE.md for the layer rules):
--   * Every source column is VARCHAR, named exactly as in the workbook. Names
--     with spaces, slashes, parentheses, or dots are double-quoted identifiers.
--   * Duplicate source names: the workbook has none. The rule is implemented
--     anyway: an occurrence N > 1 is stored as "<name>__<N>". (Occurrence is
--     the column `occurrence` in the column map.)
--   * Bronze metadata names are fixed: _batch_id, _source_file, _load_ts,
--     _record_hash. Five9's own FILE_NAME and LOAD_TIMESTAMP stay as source
--     columns; they never hold our metadata.
--   * _extra_payload VARIANT receives any column that is not in the table
--     (schema drift). See the explanation below.
--
-- Why _extra_payload (VARIANT) instead of ALTER TABLE ADD COLUMN on drift:
--   Five9 adds columns over time. With a VARIANT catch-all, a new column never
--   fails a load and needs no DDL at load time: its name and value go into the
--   payload, and CONTROL.schema_drift_log records it. When the column is
--   promoted to silver (after the column map is updated), a migration adds the
--   typed bronze column and silver reads it from there. The cost is that the
--   payload needs a parse step in silver before use, and the bronze table is a
--   little wider. Accepted, because it keeps loads from failing on drift.
--
-- Access: bronze holds raw Five9 PII (ANI, names, email, address). Restrict
--   SELECT on this schema to the load role (CLAUDE.md, Source system section).
--
-- Grain of every table: one row per source line, as received.
-- Clustering: none on bronze. Bronze is append-only and read by batch, so the
--   load is the access path; clustering would add cost without a query benefit.
-- =============================================================================

