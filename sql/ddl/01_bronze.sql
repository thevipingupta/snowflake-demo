-- -----------------------------------------------------------------------------
-- CONTROL.load_log   (one row per file load; written by the bronze procedures)
--   Grain  : one row per (batch_id, source_table, source_file, attempt).
--   Source : the load procedure itself.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS CC_DEMO.CONTROL.load_log (
    load_id VARCHAR DEFAULT UUID_STRING(),
    batch_id VARCHAR,
    source_table VARCHAR,
    source_file VARCHAR,
    rows_read NUMBER(12,0),
    rows_loaded NUMBER(12,0),
    rows_skipped_duplicate_batch NUMBER(12,0),
    status VARCHAR,            -- STARTED | SUCCEEDED | FAILED | SKIPPED_ALREADY_LOADED
    error_message VARCHAR,
    started_ts TIMESTAMP_NTZ,
    ended_ts TIMESTAMP_NTZ
);

-- -----------------------------------------------------------------------------
-- CONTROL.schema_drift_log   (one row per column first seen that is not in its table)
--   Grain  : one row per (source_table, column_name, batch_id) when a column is
--            first seen in a file that does not match the table.
--   Source : bronze load procedures, comparing the file header to the table.
--   Note   : the bronze loader writes unknown columns to _extra_payload and
--            logs them here. Columns missing from a file load as NULL and are
--            logged with detail 'MISSING_IN_FILE'.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS CC_DEMO.CONTROL.schema_drift_log (
    batch_id VARCHAR,
    source_table VARCHAR,
    column_name VARCHAR,
    first_seen_ts TIMESTAMP_NTZ,
    detail VARCHAR             -- ADDED_TO_PAYLOAD | MISSING_IN_FILE | UNMAPPED_IN_SILVER
);
